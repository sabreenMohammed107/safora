    public function run(): void
    {
        $groupIds = [];

        foreach (self::GROUPS as $order => $group) {
            $groupIds[$group['key']] = HaccpProgramGroup::updateOrCreate(['key' => $group['key']], [
                'label' => ['ar' => $group['ar'], 'en' => $group['en']],
                'icon' => $group['icon'],
                'sort_order' => $order + 1,
            ])->id;
        }

        foreach (self::PROGRAMS as $order => $program) {
            if (HaccpProgram::where('code', $program['code'])->exists()) {
                continue;
            }

            $content = collect($program)->except(['code', 'group', 'icon', 'name'])
                ->map(fn (string $text): array => ['ar' => $text])
                ->all();

            HaccpProgram::create([
                ...$content,
                'code' => $program['code'],
                'group_id' => $groupIds[$program['group']],
                'icon' => $program['icon'],
                'name' => $program['name'],
                'status' => ProgramStatus::Active,
                'is_custom' => false,
                'sort_order' => $order + 1,
            ]);
        }
    }
